import { mkdir, readFile, writeFile, copyFile, stat } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '..');
const vendor = join(root, 'site/vendor/paddleocr');
await mkdir(join(vendor, 'ort'), { recursive: true });
await mkdir(join(root, 'site/models'), { recursive: true });
await build({
  stdin: { contents: 'export { PaddleOCR } from "@paddleocr/paddleocr-js";', resolveDir: root },
  outfile: join(vendor, 'ocr-sdk-lite.js'), bundle: true, format: 'esm', platform: 'browser',
  target: 'es2022', minify: true, legalComments: 'eof', external: ['fs', 'path', 'crypto'],
  alias: { 'onnxruntime-web': 'onnxruntime-web/wasm' },
  define: { 'process.env.NODE_ENV': '"production"' },
  plugins: [{ name: 'separate-opencv', setup(builder) {
    builder.onResolve({ filter: /^@techstark\/opencv-js$/ }, () => ({ path: 'opencv', namespace: 'ready-cv' }));
    builder.onLoad({ filter: /.*/, namespace: 'ready-cv' }, () => ({ contents: 'export default globalThis.__ieltsCVModule;', loader: 'js' }));
  } }]
});
await copyFile(join(root, 'node_modules/@techstark/opencv-js/dist/opencv.js'), join(vendor, 'opencv.js'));
await copyFile(join(root, 'node_modules/@techstark/opencv-js/LICENSE'), join(vendor, 'OpenCV-LICENSE'));
for (const file of ['ort-wasm-simd-threaded.wasm', 'ort-wasm-simd-threaded.mjs']) {
  await copyFile(join(root, 'node_modules/onnxruntime-web/dist', file), join(vendor, 'ort', file));
}
const models = [
  ['PP-OCRv5_mobile_det', 4843520], ['PP-OCRv5_mobile_rec', 16701440]
];
const receipts = [];
for (const [name, expectedBytes] of models) {
  const file = `${name}_onnx_infer.tar`, target = join(root, 'site/models', file);
  if (await stat(target).then(s => s.size !== expectedBytes).catch(() => true)) {
    const url = `https://paddle-model-ecology.bj.bcebos.com/paddlex/official_inference_model/paddle3.0.0/${file}`;
    console.log(`Downloading official model: ${name}`);
    const response = await fetch(url, { signal: AbortSignal.timeout(120000) });
    if (!response.ok) throw new Error(`Model download failed: ${response.status}`);
    const bytes = new Uint8Array(await response.arrayBuffer());
    if (bytes.length !== expectedBytes) throw new Error(`Unexpected model size: ${name} (${bytes.length})`);
    await writeFile(target, bytes);
  }
  const bytes = await readFile(target);
  receipts.push({ name, file, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
}
await writeFile(join(vendor, 'model-receipts.json'), JSON.stringify(receipts, null, 2));
for (const [from, to] of [
  ['@paddleocr/paddleocr-js/package.json', 'paddleocr-package.json'],
  ['onnxruntime-web/package.json', 'onnxruntime-package.json']
]) await copyFile(join(root, 'node_modules', from), join(vendor, to));
for (const [name, url] of [
  ['PaddleOCR-LICENSE', 'https://raw.githubusercontent.com/PaddlePaddle/PaddleOCR/main/LICENSE'],
  ['onnxruntime-LICENSE', 'https://raw.githubusercontent.com/microsoft/onnxruntime/main/LICENSE']
]) {
  if (await stat(join(vendor, name)).then(s => s.size > 0).catch(() => false)) continue;
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`License download failed: ${name}`);
  await writeFile(join(vendor, name), await response.text());
}
const assetSpecs = [
  ['sdk', '识别组件', './vendor/paddleocr/ocr-sdk-lite.js', 'text/javascript'],
  ['cv', '图像处理组件', './vendor/paddleocr/opencv.js', 'text/javascript', 'https://registry.npmmirror.com/@techstark/opencv-js/4.10.0-release.1/files/dist/opencv.js'],
  ['det', '文字定位模型', './models/PP-OCRv5_mobile_det_onnx_infer.tar', 'application/octet-stream', 'https://paddle-model-ecology.bj.bcebos.com/paddlex/official_inference_model/paddle3.0.0/PP-OCRv5_mobile_det_onnx_infer.tar'],
  ['rec', '中英文识别模型', './models/PP-OCRv5_mobile_rec_onnx_infer.tar', 'application/octet-stream', 'https://paddle-model-ecology.bj.bcebos.com/paddlex/official_inference_model/paddle3.0.0/PP-OCRv5_mobile_rec_onnx_infer.tar'],
  ['runtime', '运行组件', './vendor/paddleocr/ort/ort-wasm-simd-threaded.mjs', 'text/javascript', 'https://registry.npmmirror.com/onnxruntime-web/1.30.0/files/dist/ort-wasm-simd-threaded.mjs'],
  ['wasm', '本机计算组件', './vendor/paddleocr/ort/ort-wasm-simd-threaded.wasm', 'application/wasm', 'https://registry.npmmirror.com/onnxruntime-web/1.30.0/files/dist/ort-wasm-simd-threaded.wasm']
];
const manifest = [];
for (const [key, label, path, type, source] of assetSpecs) {
  const bytes = await readFile(join(root, 'site', path));
  manifest.push({ key, label, path, type, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex'), sources: source ? [source, path] : [path] });
}
await writeFile(join(root, 'site/ocr-assets-manifest.js'), `// Generated by scripts/prepare-free-ocr.mjs; pinned public assets, never user answers.\nexport const ASSETS = ${JSON.stringify(manifest, null, 2)};\n`);
console.log('Free OCR assets prepared. No API key or paid requests are used.');
